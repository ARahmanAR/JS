// JavaScript Data Types

// 1. String
let name = "JavaScript";
let greeting = 'Hello World';
console.log("String:", name, greeting);

// 2. Number
let age = 25;
let price = 99.99;
console.log("Number:", age, price);

// 3. Boolean
let isLearning = true;
let isCompleted = false;
console.log("Boolean:", isLearning, isCompleted);

// 4. Undefined
let notDefined;
console.log("Undefined:", notDefined);

// 5. Null
let emptyValue = null;
console.log("Null:", emptyValue);

// 6. typeof operator
console.log("\nType checking:");
console.log("typeof name:", typeof name);
console.log("typeof age:", typeof age);
console.log("typeof isLearning:", typeof isLearning);
console.log("typeof notDefined:", typeof notDefined);
console.log("typeof emptyValue:", typeof emptyValue);
